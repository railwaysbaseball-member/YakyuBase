-- ============================================================
-- 0006_players_is_guest.sql
-- players に「助っ人」フラグを追加
--
-- 背景: 個人成績(/stats)には本来チームに所属していない助っ人選手も
-- 含まれてしまっている。自チームの選手と助っ人を区別し、個人成績には
-- 自チームの選手のみを表示できるようにする。
--
-- 既存選手は全員 false（自チーム）で初期化し、/players の管理画面で
-- 個別に助っ人へ切り替える想定。
--
-- 実行方法: 0001〜0005と同様、Supabase ダッシュボードの SQL Editor に
-- 貼り付けて実行。
-- ============================================================

alter table public.players
  add column if not exists is_guest boolean not null default false;
