-- ============================================================
-- 0004_fix_game140_sensei.sql
-- game-140 先生の打席データ抜け漏れ修正
--
-- 背景: 網羅テスト整備の一環で実サイトの2026年成績と全選手を突き合わせた際に
-- 発覚。先生のgame-140の打席が実サイトでは4打席（二ゴ,右飛,三振,投ゴ）だが、
-- 取り込み時は3打席（二ゴ,右飛,投ゴ）しか記録されておらず、5回の三振が
-- 抜け落ちていた（安打数には影響しないため打率.111自体はズレないが、
-- 打席・打数が実サイトと1件ずつ不一致になっていた）。
--
-- 実行方法: 0001〜0003と同様、Supabase ダッシュボードの SQL Editor に
-- 貼り付けて実行。
-- ============================================================

update public.game_batting_stats
set
  plate_results = '[{"inning":1,"result":"二ゴ"},{"inning":3,"result":"右飛"},{"inning":5,"result":"三振"},{"inning":7,"result":"投ゴ"}]'::jsonb,
  plate_appearances = 4,
  at_bats = 4
where game_id = 'game-140' and player_id = '先生';
